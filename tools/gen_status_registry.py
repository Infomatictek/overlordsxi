#!/usr/bin/env python3
"""Regenerates overlords_status_registry.lua and custom_status_effects_sync.sql
from modules/custom/data/custom_status_manifest.json (single source of truth).

Also (idempotently) backfills isDebuff / isShared / soulKey on every manifest entry.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "modules/custom/data/custom_status_manifest.json"
LUA_OUT = ROOT / "modules/custom/lua/overlords_status_registry.lua"
SQL_OUT = ROOT / "modules/custom/sql/custom_status_effects_sync.sql"

PREFIX_SOUL = {
    "COMMANDER": "commander", "BERSERKER": "berserker", "GLADIATOR": "spartan", "SPARTAN": "spartan",
    "INQUISITOR": "inquisitor", "SPELLBLADE": "spellblade", "LIFEBINDER": "lifebinder",
    "CHIWEAVER": "chiweaver", "ADVENTURER": "adventurer", "MUSICIAN": "musician", "MINSTREL": "minstrel",
    "RONIN": "ronin", "IMP": "imperial", "WARLORD": "warlord", "AEGIS": "aegistemplar",
    "HOLY": "aegistemplar", "KAGEMUSHA": "kagemusha", "ALPHA": "alphawarden", "CRIMSON": "crimsonduelist",
    "BLOOD": "dreadnought", "DREAD": "dreadnought", "CHITIN": "azurebastion", "AZURE": "azurebastion",
    "DIAMOND": "azurebastion", "SOLACE": "medic", "SACRED": "medic", "DIVINE": "medic",
    "LIGHTS": "lightbringer", "CRUSADERS": "lightbringer", "OSMOTIC": "magus", "SANGUINE": "bloodmaiden",
    "CELESTIAL": "celestial", "CLOCKWORK": "clockwork", "BARKSKIN": "geomancer", "CANOPY": "geomancer",
    "DRAGONSCALE": "wyvernheart", "HOUSE": "gambler", "CARD": "gambler", "EOS": "faerie",
}
SPECIAL = {"AZURE_CATALYST": "magus", "SOLACE_WARD": "wyvernheart"}
SPECIAL.pop("SOLACE_WARD")


def soul_for(key: str) -> str:
    if key.startswith("EFF_OX_"):
        return ""
    if key in SPECIAL:
        return SPECIAL[key]
    return PREFIX_SOUL.get(key.split("_")[0], "")


def main() -> None:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    effects = sorted(data["effects"], key=lambda e: e["effectId"])
    for e in effects:
        e.setdefault("isDebuff", e["visualTheme"]["role"] == "debuff")
        e.setdefault("isShared", e["key"].startswith("EFF_OX_"))
        e.setdefault("soulKey", soul_for(e["key"]))
    ids = [e["effectId"] for e in effects]
    icons = [e["iconId"] for e in effects]
    assert len(set(ids)) == len(ids), "duplicate effectId"
    assert len(set(icons)) == len(icons), "duplicate iconId"
    assert all(1 <= i < 639 and i not in (255, 511) for i in icons)
    data["effects"] = effects
    MANIFEST.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    lua = [
        "-----------------------------------",
        "-- OverlordsXI Central Custom Status Effect Registry",
        "-- GENERATED by tools/gen_status_registry.py from modules/custom/data/custom_status_manifest.json",
        "-- Registers xi.effect.<KEY> and xi.overlords.statusIcons[effectId] = iconId",
        "-----------------------------------",
        "require('modules/module_utils')",
        "-----------------------------------",
        "local m = Module:new('overlords_status_registry')",
        "",
        "xi = xi or {}",
        "xi.effect = xi.effect or {}",
        "xi.overlords = xi.overlords or {}",
        "xi.overlords.statusIcons = xi.overlords.statusIcons or {}",
        "xi.overlords.statusRegistry = xi.overlords.statusRegistry or {}",
        "",
        "local ENTRIES =",
        "{",
    ]
    for e in effects:
        al = ", ".join(f"'{a}'" for a in e["aliases"])
        dn = e["displayName"].replace("'", "\\'")
        lua.append(
            f"    {{ effectId = {e['effectId']}, iconId = {e['iconId']:3d}, key = '{e['key']}', "
            f"name = '{e['name']}', displayName = '{dn}', isDebuff = {str(e['isDebuff']).lower()}, aliases = {{ {al} }} }},"
        )
    lua += [
        "}",
        "",
        "for _, entry in ipairs(ENTRIES) do",
        "    xi.effect[entry.key] = entry.effectId",
        "    for _, alias in ipairs(entry.aliases) do",
        "        xi.effect[alias] = entry.effectId",
        "    end",
        "    xi.overlords.statusIcons[entry.effectId] = entry.iconId",
        "    xi.overlords.statusRegistry[entry.effectId] = entry",
        "end",
        "",
        "function xi.overlords.getStatusIcon(effectId, fallback)",
        "    if effectId ~= nil and xi.overlords.statusIcons[effectId] ~= nil then",
        "        return xi.overlords.statusIcons[effectId]",
        "    end",
        "    return fallback or effectId",
        "end",
        "",
        "return m",
        "",
    ]
    LUA_OUT.write_text("\n".join(lua), encoding="utf-8", newline="\n")

    sql = [
        "-- ---------------------------------------------------------------------------",
        "-- OverlordsXI Custom Status Effects Sync (Idempotent)",
        "-- GENERATED by tools/gen_status_registry.py from custom_status_manifest.json",
        "-- ---------------------------------------------------------------------------",
        "",
        "CREATE TABLE IF NOT EXISTS `status_effects` (",
        "    `id` SMALLINT(5) UNSIGNED NOT NULL,",
        "    `name` VARCHAR(50) NOT NULL,",
        "    `flags` INT(10) UNSIGNED NOT NULL DEFAULT 0,",
        "    `type` SMALLINT(5) UNSIGNED NOT NULL DEFAULT 0,",
        "    `min_duration` SMALLINT(5) UNSIGNED NOT NULL DEFAULT 0,",
        "    `icon` SMALLINT(5) UNSIGNED NOT NULL DEFAULT 0,",
        "    PRIMARY KEY (`id`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;",
        "",
        "INSERT INTO `status_effects` (`id`, `name`, `flags`, `type`, `min_duration`, `icon`) VALUES",
    ]
    rows = [
        f"    ({e['effectId']}, '{e['name']}', {e['flagMask']}, {e['type']}, {e['minDuration']}, {e['iconId']})"
        for e in effects
    ]
    sql.append(",\n".join(rows))
    sql += [
        "ON DUPLICATE KEY UPDATE",
        "    `name` = VALUES(`name`),",
        "    `flags` = VALUES(`flags`),",
        "    `type` = VALUES(`type`),",
        "    `min_duration` = VALUES(`min_duration`),",
        "    `icon` = VALUES(`icon`);",
        "",
    ]
    SQL_OUT.write_text("\n".join(sql), encoding="utf-8", newline="\n")
    print(f"Regenerated registry + SQL for {len(effects)} effects")


if __name__ == "__main__":
    main()
