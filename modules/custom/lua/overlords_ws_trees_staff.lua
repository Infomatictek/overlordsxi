local H = require('modules/custom/lua/overlords_ws_tree_helpers')
local regB, node = H.regBaseline, H.node

local SENSEI_EFFECTS = { xi.effect.COUNTERSTANCE, xi.effect.DODGE, xi.effect.FOCUS, xi.effect.PERFECT_COUNTER, xi.effect.INNER_STRENGTH }
local SCH_EFFECTS    = { xi.effect.LIGHT_ARTS, xi.effect.DARK_ARTS, xi.effect.ADDENDUM_WHITE, xi.effect.ADDENDUM_BLACK, xi.effect.AFFLATUS_SOLACE, xi.effect.AFFLATUS_MISERY }
local WAR_EFFECTS    = { xi.effect.BERSERK, xi.effect.WARCRY, xi.effect.AGGRESSOR, xi.effect.RETALIATION, xi.effect.RESTRAINT }

local function senseiStance(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
    eff.stance = {
        jobSpec = 'sensei',
        effects = SENSEI_EFFECTS,
        wsd     = eff.stWsd,
        atkPct  = eff.stAtk,
        crit    = eff.stCrit,
    }
    eff.stWsd, eff.stAtk, eff.stCrit = nil, nil, nil
    return node(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
end

local function schStance(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
    eff.stance = {
        schSpec  = { 'medic', 'sage' },
        petAlive = true,
        effects  = SCH_EFFECTS,
        wsd      = eff.stWsd,
        matt     = eff.stMatt,
        macc     = eff.stMacc,
    }
    eff.stWsd, eff.stMatt, eff.stMacc = nil, nil, nil
    return node(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
end

local function warStance(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
    eff.stance = {
        jobSpec = { 'commander', 'berserker' },
        effects = WAR_EFFECTS,
        wsd     = eff.stWsd,
        atkPct  = eff.stAtk,
        crit    = eff.stCrit,
        tpBonus = eff.stTp,
    }
    eff.stWsd, eff.stAtk, eff.stCrit, eff.stTp = nil, nil, nil, nil
    return node(t, c, k, name, mr, zeroDesc, rankDesc, eff, req)
end

-- Helper for Sensei counter/parry/eva post-buffs
local function senseiBuff(dur, counterTbl, parryTbl, evaTbl)
    local mods = {}
    if counterTbl then table.insert(mods, { mod = xi.mod.COUNTER, val = counterTbl }) end
    if parryTbl   then table.insert(mods, { mod = xi.mod.INQUARTATA, val = parryTbl }) end
    if evaTbl     then table.insert(mods, { mod = xi.mod.EVA, val = evaTbl }) end
    return { effect = xi.effect.COUNTERSTANCE, duration = dur or 15, mods = mods }
end

